"""Validate and publish one authored knowledge card per bundled subsection."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def module_text(rows):
    return '// Generated by scripts/section_knowledge.py; edit data/section-knowledge.json.\n' + \
        'export const sectionKnowledge = ' + json.dumps(rows, ensure_ascii=False, indent=2) + ';\n' + """
const index = new Map(sectionKnowledge.map(row => [row.subjectId + ':' + row.sectionId, row]));
export function sectionKnowledgeCard(subjectId, sectionId) {
  return index.get(subjectId + ':' + sectionId) ?? null;
}
export function sectionCardsForBank(bank) {
  const available = new Map();
  for (const subject of bank.subjects) {
    const visit = (chapters, parent = null) => {
      for (const chapter of chapters) {
        const parentId = chapter.parentId ?? parent;
        if (parentId) available.set(subject.id + ':' + chapter.id, {name:chapter.name,parentId});
        if (chapter.children) visit(chapter.children, chapter.id);
      }
    };
    visit(subject.chapters);
  }
  const originalOrder = new Map(sectionKnowledge.map((row, i) => [row.sectionId, i]));
  return sectionKnowledge.filter(row => {
    const chapter = available.get(row.subjectId + ':' + row.sectionId);
    return chapter?.name === row.sourceTitle && chapter.parentId === row.chapterId;
  }).sort((a,b) => a.subjectId === b.subjectId && a.chapterId === b.chapterId && /^\\d/.test(a.title) && /^\\d/.test(b.title)
    ? a.title.localeCompare(b.title, 'zh-CN', {numeric:true})
    : originalOrder.get(a.sectionId) - originalOrder.get(b.sectionId));
}
"""


def publish(check=False, root=ROOT):
    data = json.loads((root / 'data/section-knowledge.json').read_text())
    bank = json.loads((root / 'dist/data/bank.json').read_text())
    expected = {}
    for subject in bank['subjects']:
        def visit(chapters, parent=None):
            for chapter in chapters:
                parent_id = chapter.get('parentId') or parent
                if parent_id:
                    expected[subject['id'], chapter['id']] = (chapter['name'], parent_id)
                visit(chapter.get('children', []), chapter['id'])
        visit(subject['chapters'])
    actual = {}
    for row in data['sections']:
        key = row['subjectId'], row['sectionId']
        if key in actual:
            raise ValueError('Duplicate section card: ' + str(key))
        actual[key] = row['sourceTitle'], row['chapterId']
        for field in ['overview', 'formula', 'condition', 'example', 'warning']:
            if not isinstance(row.get(field), str) or len(row[field].strip()) < 8:
                raise ValueError('Incomplete section card: ' + str(key) + ' ' + field)
        for exercise in row.get('exercises', []):
            if exercise.get('type') not in {'填空', '解答', '判断'} or any(
                not isinstance(exercise.get(field), str) or not exercise[field].strip()
                for field in ('prompt', 'solution')
            ):
                raise ValueError('Incomplete section exercise: ' + str(key))
    if actual != expected:
        raise ValueError('Knowledge cards do not exactly match the current subsection catalog')
    path = root / 'dist/section-knowledge.mjs'
    content = module_text(data['sections'])
    if check:
        if path.read_text() != content:
            raise ValueError('Run python3 scripts/section_knowledge.py to publish section cards')
    else:
        path.write_text(content)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    publish(parser.parse_args().check)
