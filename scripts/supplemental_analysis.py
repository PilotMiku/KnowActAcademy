"""Publish authored explanations separately from immutable source questions."""
import argparse
import json
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


@lru_cache(maxsize=4)
def entries(root=ROOT):
    return json.loads((root / 'data/supplemental-analysis.json').read_text())['entries']


def review_required(question, records=None):
    row = (entries() if records is None else records).get(question.get('id'))
    return bool(row and row['status'] == 'review' and question.get('analysisMissing')
                and question.get('answer') == row['referenceAnswer']
                and question.get('source', {}).get('sha256') == row['sourceSha256'])


def module_text(records):
    data = json.dumps(records, ensure_ascii=False, indent=2)
    return '// Generated by scripts/supplemental_analysis.py; edit data/supplemental-analysis.json.\n' + \
        'export const supplementalAnalyses = ' + data + ';\n' + """
export function supplementalAnalysis(question) {
  const row = supplementalAnalyses[question?.id];
  if (!row || !question.analysisMissing || question.answer !== row.referenceAnswer) return null;
  const original = question.source?.sha256 === row.sourceSha256;
  const catalog = question.contentChunk && ['pdf', 'html'].includes(question.source?.format) && !question.source.sha256;
  return original || catalog ? row : null;
}
export function analysisReview(question) {
  const row = supplementalAnalysis(question);
  return row?.status === 'review' ? row : null;
}
"""


def publish(check=False, root=ROOT):
    records = entries(root)
    bank = json.loads((root / 'dist/data/bank.json').read_text())
    questions = {q['id']: q for q in bank['questions']}
    for qid, row in records.items():
        question = questions[qid]
        if (not question.get('analysisMissing') or question['answer'] != row['referenceAnswer']
                or question['source']['sha256'] != row['sourceSha256']):
            raise ValueError('Supplemental explanation no longer matches its source: ' + qid)
    path = root / 'dist/supplemental-analysis.mjs'
    text = module_text(records)
    if check:
        if path.read_text() != text:
            raise ValueError('Run python3 scripts/supplemental_analysis.py to publish explanations')
    else:
        path.write_text(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    publish(parser.parse_args().check)
