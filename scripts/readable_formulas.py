"""Publish source-bound, visually checked formula transcriptions as a display overlay."""
import argparse
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]


def publish(check=False):
    records = json.loads((ROOT/'data/readable-formulas.json').read_text())['records']
    packs = {}
    for key, row in records.items():
        if not re.fullmatch('[a-f0-9]{24}', key) or row['review'] != 'visually-checked-original' or not row['latex'].strip():
            raise ValueError('无效的已核对公式 '+key)
        path = ROOT/'dist/question-figures'/(key[:2]+'-'+row['version']+'.json')
        if path not in packs:
            packs[path] = json.loads(path.read_text())['figures']
        if key not in packs[path]:
            raise ValueError('已核对公式缺少对应原图 '+key)
    payload = '// Generated by scripts/readable_formulas.py; original source images stay unchanged.\n'
    payload += 'export const readableFormulas = Object.freeze('+json.dumps(records, ensure_ascii=False, separators=(',', ':'))+');\n'
    payload += '''export function readableFormula(id, version) {
  const row = readableFormulas[id];
  return row && row.version === version ? row.latex : null;
}
'''
    target = ROOT/'dist/readable-formulas.mjs'
    if check:
        if not target.exists() or target.read_text() != payload:
            raise ValueError('清晰公式与校对记录不一致，请运行 scripts/readable_formulas.py')
    else:
        target.write_text(payload)
    return len(records)

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check', action='store_true')
    print(publish(parser.parse_args().check))
