"""Reproducible practice estimates; source defaults never count as ratings."""
import collections
import html
import json
from pathlib import Path
import re
import argparse
ROOT = Path(__file__).resolve().parents[1]


def estimate(question):
    topic = ' '.join(question.get('tags', [])[:2])
    stem = html.unescape(re.sub(r'<[^>]*>', ' ', question['stem']))
    analysis = html.unescape(re.sub(r'<[^>]*>', ' ', question.get('analysis', '')))
    stars, reasons = 2, ['常规概念辨析或直接计算']
    if re.search('重积分|曲线积分|曲面积分|级数|中值定理|微分方程|二次型|特征|相似|秩|Cramer|隐函数|高阶|参数方程', topic):
        stars, reasons = 3, ['本小节通常需要方法选择或多步运算']
    if re.search('格林|高斯|斯托克斯|傅里叶|一致收敛|展开成幂级数|幂级数展开|第二型曲面', topic):
        stars, reasons = 4, ['本小节涉及综合公式及适用条件']
    if re.search('定义|概念|基本公式', topic) and re.search('属于|称为|定义为|表示的是|下列.*正确', stem):
        stars, reasons = 1, ['主要考查基本概念的识别']
    if re.search('证明|证实|试证', stem):
        stars = min(5, stars + 1); reasons.append('题干要求论证')
    if re.search('存在.*使|至少存在|任意.*恒成立|充要条件|必要充分条件|讨论.*参数|讨论.*取值', stem):
        stars = min(5, stars + 1); reasons.append('含条件推理或参数讨论')
    methods = [r'分部积分', r'换元|变量代换', r'洛必达|L.Hospital', r'泰勒|Taylor', r'夹逼', r'中值定理', r'分类讨论|分情况', r'反证', r'数学归纳', r'正交变换', r'特征值', r'格林|高斯|斯托克斯']
    if sum(bool(re.search(p, analysis)) for p in methods) >= 2:
        stars = min(5, stars + 1); reasons.append('解析同时涉及多种解法要点')
    # Missing text and raster size are not proxies for mathematical difficulty.
    return stars, '；'.join(reasons)


def publish(check=False):
    bank = json.loads((ROOT/'dist/data/bank.json').read_text())
    sources, reasons, records = [], [], {}
    for q in bank['questions']:
        stars, reason = estimate(q)
        source = [q['source']['sha256'], q['source']['format']]
        if source not in sources: sources.append(source)
        if reason not in reasons: reasons.append(reason)
        records[q['id']] = [stars, reasons.index(reason), sources.index(source)]
    content = '// Generated by scripts/question_difficulty.py; estimates, not calibrated exam ratings.\n'
    for name, value in [('sources', sources), ('reasons', reasons), ('ratings', records)]:
        content += 'const '+name+' = '+json.dumps(value, ensure_ascii=False, separators=(',', ':'))+';\n'
    content += """export function estimatedDifficulty(q) {
  const row = Object.hasOwn(ratings, q.id) ? ratings[q.id] : null;
  if (!row) return null;
  const source = sources[row[2]];
  if (q.source?.format !== source[1] || (q.source?.sha256 ? q.source.sha256 !== source[0] : !q.contentChunk)) return null;
  return { stars:row[0], reason:reasons[row[1]], origin:'自动初评' };
}
"""
    target = ROOT/'dist/question-difficulty.mjs'
    if check:
        if not target.exists() or target.read_text() != content:
            raise ValueError('难度初评与题库不一致，请运行 scripts/question_difficulty.py')
    else:
        target.write_text(content)
    return dict(collections.Counter(row[0] for row in records.values()))

if __name__ == '__main__':
    parser = argparse.ArgumentParser();parser.add_argument('--check', action='store_true')
    print(publish(parser.parse_args().check))
