import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium, browserOptions, baseURL, revealPracticeOptions } from './browser-helpers.mjs';
import { filterQuestions } from '../dist/core.mjs';

const browser = await chromium.launch(browserOptions), errors = [], report = [];
try {
  const page = await browser.newPage({ reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  for (const viewport of [{ width: 390, height: 844 }, { width: 320, height: 568 }, { width: 1440, height: 1000 }]) {
    await page.setViewportSize(viewport);
    await page.goto(baseURL + '/#/practice');
    const start = page.locator('[data-action="start-practice"][data-mode="sequential"]');
    await start.waitFor();
    const box = await start.boundingBox();
    assert.ok(box.y >= 0 && box.y + box.height <= viewport.height, JSON.stringify({ viewport, box }));
    assert.equal(await page.locator('.practice-options').evaluate(el => el.open), false);
    assert.equal(await page.locator('.practice-progress').evaluate(el => el.open), false);
    assert.equal(await page.locator('.chapter-grid').count(), 0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    report.push({ viewport, startTop: box.y, startHeight: box.height });
    if (viewport.width === 390) await page.screenshot({ path: 'artifacts/practice-first-screen-mobile.png' });
  }
  await page.locator('#subject-filter').selectOption('linear');
  await page.locator('#chapter-filter').selectOption('linear-chapter-1');
  await revealPracticeOptions(page);
  await page.locator('#type-filter').selectOption('single');
  await page.locator('#type-filter').selectOption('');
  assert.equal(await page.locator('.practice-options').evaluate(el => el.open), true);
  await page.locator('#type-filter').selectOption('single');
  await page.locator('#random-distribution').selectOption('balanced');
  await page.locator('#practice-status').selectOption('unseen');
  const expected = await page.evaluate(() => location.hash);
  await page.locator('.practice-view-switch a').filter({ hasText: '章节目录' }).click();
  await page.locator('.chapter-grid').waitFor();
  assert.equal(await page.locator('[data-action="practice-one"]').count(), 0);
  assert.equal(await page.locator('.subject-label').innerText(), '线性代数');
  await page.reload();
  await page.locator('.chapter-grid').waitFor();
  await page.locator('.practice-view-switch a').filter({ hasText: '题目列表' }).click();
  await page.locator('[data-action="practice-one"]').first().waitFor();
  for (const key of ['subject', 'chapter', 'type', 'distribution', 'status'])
    assert.equal(new URLSearchParams((await page.evaluate(() => location.hash)).split('?')[1]).get(key), new URLSearchParams(expected.split('?')[1]).get(key));
  assert.equal(await page.locator('#type-filter').inputValue(), 'single');
  assert.equal(await page.locator('.practice-options').evaluate(el => el.open), true);
  await page.locator('.practice-progress > summary').click();
  await page.locator('.learning-progress').waitFor();
  await page.locator('[data-action="start-practice"][data-mode="random"]').click();
  await page.locator('.question-main').waitFor();
  const saved = await page.evaluate(async () => (await import('./storage.mjs')).readSavedData());
  const selected = saved.bank.questions.filter(q => q.subjectId === 'linear' && q.type === 'single');
  assert.ok(saved.state.practice.questionIds.length > 25);
  assert.ok(saved.state.practice.questionIds.every(id => selected.some(q => q.id === id)));
  await page.locator('[data-action="exit-practice"]').click();
  await page.locator('[data-action="resume-practice"]').click();
  await page.locator('.question-main').waitFor();
  assert.equal((await page.evaluate(async () => (await import('./storage.mjs')).readSavedState())).practice.id, saved.state.practice.id);

  await page.locator('[data-action="exit-practice"]').click();
  await page.setViewportSize({ width: 320, height: 568 });
  const chooseChapters = page.getByRole('button', { name: '多选章节', exact: true });
  await chooseChapters.click();
  const picker = page.getByRole('dialog', { name: '多选练习章节' });
  const roots = ['linear-chapter-1', 'linear-chapter-2'];
  const childIds = roots.map(id => saved.bank.subjects.find(s => s.id === 'linear').chapters.find(c => c.parentId === id).id);
  const chapterCheckbox = id => picker.locator(`[data-practice-chapter][value="${id}"]`);
  const chapterGroup = id => picker.locator('.preparation-scope-group').filter({ has: page.locator(`[data-practice-chapter][value="${id}"]`) });
  assert.equal(await chapterCheckbox(roots[0]).isChecked(), true);
  await chapterGroup(roots[0]).locator('summary').click();
  assert.equal(await chapterCheckbox(childIds[0]).isChecked(), true);
  assert.equal(await chapterCheckbox(childIds[0]).isDisabled(), true);
  await chapterGroup(roots[1]).locator('summary').click();
  await chapterCheckbox(childIds[1]).check();
  assert.equal(await chapterCheckbox(roots[1]).evaluate(el => el.indeterminate), true);
  assert.equal(await picker.locator('#practice-chapter-count').innerText(), '已选 2 个章节');
  assert.equal(await picker.evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await picker.getByRole('button', { name: '应用章节' }).click();
  await page.locator('.practice-scope-summary').getByText('已选 2 个章节').waitFor();
  const multiScopeURL = page.url();
  await page.reload();
  await chooseChapters.click();
  assert.equal(await chapterCheckbox(childIds[1]).isChecked(), true);
  await chapterCheckbox(childIds[1]).uncheck();
  await picker.getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(page.url(), multiScopeURL);

  const random = page.getByRole('button', { name: '随机刷题', exact: true });
  await random.click();
  await page.locator('.question-main').waitFor();
  const multi = (await page.evaluate(async () => (await import('./storage.mjs')).readSavedState())).practice;
  const expectedPools = [roots[0], childIds[1]].map(chapterId => filterQuestions(saved.bank, { subjectId: 'linear', chapterId, type: 'single' }).map(q => q.id));
  assert.deepEqual([...multi.questionIds].sort(), expectedPools.flat().sort());
  const firstPool = new Set(expectedPools[0]);
  assert.ok(multi.questionIds.slice(0, 4).every((id, i, ids) => i === 0 || firstPool.has(id) !== firstPool.has(ids[i - 1])));
  await page.reload();
  const jump = page.locator('[data-question-jump]');
  await jump.getByLabel('跳至题号').fill(String(multi.questionIds.length));
  await jump.getByRole('button', { name: '跳转' }).click();
  await page.getByRole('button', { name: '完成本组' }).click();
  await page.getByRole('button', { name: '返回章节选择' }).click();
  await random.waitFor();
  assert.equal(page.url(), multiScopeURL);
  await random.click();
  await page.locator('.question-main').waitFor();
  const repeated = (await page.evaluate(async () => (await import('./storage.mjs')).readSavedState())).practice;
  assert.notEqual(repeated.id, multi.id);
  assert.deepEqual([...repeated.questionIds].sort(), [...multi.questionIds].sort());
  await page.locator('[data-action="exit-practice"]').click();
  await chooseChapters.click();
  await picker.getByRole('button', { name: '清空选择' }).click();
  await picker.getByRole('button', { name: '应用章节' }).click();
  await page.waitForURL(url => !url.hash.includes('scopeChapter'));
  assert.equal(await random.isDisabled(), true);

  await page.goto(baseURL + '/#/practice?q=' + encodeURIComponent('没有这样的题目-qzx987'));
  await page.getByRole('heading', { name: '没有符合条件的题目' }).waitFor();
  assert.equal(await page.locator('[data-action="start-practice"][data-mode="sequential"]').isDisabled(), true);
  await page.getByRole('link', { name: '清除筛选', exact: true }).click();
  await page.locator('.practice-start').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-action="toggle-theme"]').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'artifacts/practice-first-screen-mobile-dark.png' });

  const mixEntry = page.locator('.method-mix-entry');
  assert.match(await mixEntry.innerText(), /换元积分与分部积分 · 8 题/);
  await mixEntry.getByRole('button', { name: '开始混练' }).click();
  await page.getByRole('heading', { name: '易混题型混练', exact: true }).waitFor();
  const question = page.locator('.question-main');
  await question.waitFor();
  const mix = (await page.evaluate(async () => (await import('./storage.mjs')).readSavedState())).practice;
  assert.equal(mix.mode, 'method-mix');
  assert.equal(mix.questionIds.length, 8);
  assert.equal(await page.locator('.source-info, .method-mix-feedback, [data-action="question-learning"]').count(), 0);
  const q = saved.bank.questions.find(q => q.id === mix.questionIds[0]);
  await question.locator(`[data-action="answer-option"][data-value="${q.answer}"]`).click();
  await page.getByRole('button', { name: '确认答案', exact: true }).click();
  const method = q.chapterId === 's-6dbdf44fd58a' ? '换元积分' : '分部积分';
  const feedback = page.locator('.method-mix-feedback');
  await feedback.getByText(`选法依据 · ${method}`, { exact: true }).waitFor();
  assert.ok(await feedback.locator('.katex').count());
  await page.reload();
  await feedback.getByText(`选法依据 · ${method}`, { exact: true }).waitFor();
  assert.equal(await question.getAttribute('data-question-id'), q.id);
  await page.getByRole('button', { name: '下一题', exact: true }).click();
  await page.locator(`.question-main[data-question-id="${mix.questionIds[1]}"]`).waitFor();
  assert.equal(await page.locator('.source-info, .method-mix-feedback').count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button', { name: '选择练习', exact: true }).click();
  await mixEntry.getByRole('button', { name: '开始混练' }).waitFor();
  const topic = page.getByLabel('易混题型混练', { exact: true });
  assert.equal(await topic.locator('option').count(), 18);
  await topic.selectOption(JSON.stringify(['linear', 'linear-chapter-1']));
  await mixEntry.getByRole('button', { name: '开始混练' }).click();
  await question.waitFor();
  const chapterMix = (await page.evaluate(async () => (await import('./storage.mjs')).readSavedState())).practice;
  const linearChapter = new Set(filterQuestions(saved.bank, { subjectId: 'linear', chapterId: 'linear-chapter-1' }).map(q => q.id));
  assert.ok(chapterMix.questionIds.length >= 2 && chapterMix.questionIds.every(id => linearChapter.has(id)));
  await page.locator('.page-head .subtitle').filter({ hasText: /线性代数.*行列式/ }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  await writeFile('artifacts/practice-layout-report.json', JSON.stringify({ screens: report, filterPersistence: true, randomAllAndResume: true, mixedChaptersAndRepeat: true, integralMethodMix: true, emptyScope: true, pageErrors: errors }, null, 2));
  console.log('Practice layout passed:', JSON.stringify(report));
} finally { await browser.close(); }
