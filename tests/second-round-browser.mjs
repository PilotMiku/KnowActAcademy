import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium,browserOptions,baseURL } from './browser-helpers.mjs';
const browser=await chromium.launch(browserOptions), errors=[], report={};
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(baseURL+'/#/calendar');
  await page.locator('#revision-plan-form').waitFor();
  for(const root of await page.locator('#revision-scope .preparation-root input').all()) await root.uncheck();
  const section=page.locator('[data-revision-chapter][value="s-f3c2285366b2"]');
  await section.locator('xpath=ancestor::details[1]/summary').click();
  await section.check();
  assert.equal(await page.locator('#revision-scope .preparation-root input').first().evaluate(el=>el.indeterminate),true);
  assert.match(await page.locator('#revision-scope-summary').innerText(),/已选 56 道可评分题/);
  await page.locator('[name="minutesPerDay"]').fill('10');
  await page.locator('#revision-plan-form [type="submit"]').click();
  await page.locator('.revision-overview').waitFor();
  const overview = await page.locator('.revision-overview').innerText();
  assert.match(overview,/每天 10 分钟/);
  assert.match(overview,/今天约 5 题/);
  await page.goto(baseURL+'/#/');
  await page.locator('.daily-tasks').waitFor();
  assert.match(await page.locator('.daily-task-head').innerText(),/还差 5 题/);
  assert.equal(await page.locator('[data-action="goal"]').count(),0);
  await page.locator('[data-action="revision-practice"]').click();
  await page.locator('.question-main').waitFor();
  await page.locator('[data-action="question-learning"]').click();
  await page.locator('#learning-panel').waitFor({state:'visible'});
  assert.match(await page.locator('#learning-panel').innerText(),/三角函数重要极限/);
  assert.equal(await page.locator('#dialog').evaluate(el=>el.open),false);
  await page.keyboard.press('Escape');
  await page.locator('#learning-panel').waitFor({state:'hidden'});
  await page.locator('.method-hint summary').click();
  assert.equal(await page.locator('.hint-step:visible').count(),0);
  await page.locator('[data-action="reveal-hint"]').click();
  assert.equal(await page.locator('.hint-step:visible').count(),1);
  await page.evaluate(()=>document.activeElement?.blur());
  await page.keyboard.press('c');
  assert.equal(await page.locator('.option.selected').getAttribute('data-value'),'C');
  await page.evaluate(()=>document.activeElement?.blur());
  await page.keyboard.press('Enter');
  await page.locator('.result-box').waitFor();
  await page.locator('.question-notes summary').click();
  const note=page.locator('[data-question-note]');
  await note.fill('A D Enter 不应触发答题');
  const before=await page.locator('.question-main').getAttribute('data-question-id');
  await note.press('ArrowRight');
  assert.equal(await page.locator('.question-main').getAttribute('data-question-id'),before);
  await note.press('Enter');
  assert.equal(await page.locator('.question-main').getAttribute('data-question-id'),before);
  await note.blur();
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(id=>document.querySelector('.question-main')?.dataset.questionId && document.querySelector('.question-main').dataset.questionId!==id,before);
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(id=>document.querySelector('.question-main')?.dataset.questionId===id,before);
  report.unifiedTaskScopeHintsAndKeyboard=true;
  await page.locator('[data-action="question-learning"]').click();
  await page.waitForFunction(()=>!document.querySelector('#toast').classList.contains('show'));
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo({top:0,behavior:'instant'});});
  await page.screenshot({path:'artifacts/learning-panel-desktop.png',animations:'disabled',fullPage:true});
  for(const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.equal(await page.locator('#learning-panel').isVisible(),true);
    const bar=await page.locator('.question-actions').boundingBox();
    assert.ok(bar.y+bar.height<=845);
  }
  await page.locator('[data-action="close-learning"]').click();
  await page.locator('#learning-panel').waitFor({state:'hidden'});
  await page.locator('[data-action="question-learning"]').click();
  await page.waitForFunction(()=>{
    const question=document.querySelector('.question-main > .question-title')?.getBoundingClientRect();
    const panel=document.querySelector('#learning-panel')?.getBoundingClientRect();
    return question && panel && Math.abs(question.top - 90) < 2 && question.bottom < panel.top;
  });
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await page.screenshot({path:'artifacts/learning-panel-mobile.png',animations:'disabled'});
  const panelQuestion=await page.locator('.question-main').getAttribute('data-question-id');
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(id=>document.querySelector('.question-main')?.dataset.questionId && document.querySelector('.question-main').dataset.questionId!==id,panelQuestion);
  await page.keyboard.press('Escape');
  await page.locator('#learning-panel').waitFor({state:'hidden'});
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.action),'question-learning');
  assert.deepEqual(errors,[]);
  await writeFile('artifacts/second-round-report.json',JSON.stringify(report,null,2));
  console.log('Second round learning flow passed:',JSON.stringify(report));
} finally { await browser.close(); }
